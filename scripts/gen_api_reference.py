"""Generate docs/API_REFERENCE.md from the live OpenAPI schema of the FastAPI app."""
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.environ.setdefault("CAREERPILOT_DATA_DIR", tempfile.mkdtemp(prefix="cp_gen_"))
os.environ.setdefault("CAREERPILOT_SCHEDULER_ENABLED", "false")
sys.path.insert(0, str(ROOT / "services" / "api" / "src"))

from careerpilot.api.app import create_app  # noqa: E402

METHODS = ("get", "post", "put", "patch", "delete")


def main() -> int:
    spec = create_app().openapi()
    groups: dict[str, list[tuple[str, str, dict]]] = {}
    for path, item in sorted(spec["paths"].items()):
        for m in METHODS:
            op = item.get(m)
            if op:
                groups.setdefault((op.get("tags") or ["other"])[0], []).append((m.upper(), path, op))
    n = sum(len(v) for v in groups.values())
    out = ["# API reference", "",
           "Generated by `python scripts/gen_api_reference.py` from the live OpenAPI schema. "
           "Interactive docs: `/docs` on a running backend. Behavioural contract: "
           "`docs/API_CONTRACT.md`.", "", f"{n} operations.", ""]
    for tag in sorted(groups):
        out += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|"]
        for m, path, op in groups[tag]:
            summ = (op.get("summary") or op.get("operationId") or "").replace("|", "/")
            out.append(f"| {m} | `{path}` | {summ} |")
        out.append("")
    (ROOT / "docs" / "API_REFERENCE.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/API_REFERENCE.md ({n} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
